package generator

import (
	"embed"
	"fmt"
	"io"
	"io/fs"
	"os"
	"reflect"
	"strings"
	"text/template"

	"github.com/wandelbotsgmbh/nova-cli/pkg/utils"
)

const (
	folderTemplatePrefix = "__"
	folderTemplateSuffix = "__"
	templateSuffix       = ".tpl"
	templatePrefix       = "tpl."
)

type BasicAuth struct {
	Username string
	Password string
}

type InstanceInformation struct {
	// The host under which the nova api is reachable
	NovaApiHost string
	// Basic Auth credentials for accessing virtual nova instances
	BasicAuth BasicAuth
	// The name of the cell, the plugin should connect with/live in
	CellName string
	// Access token received via oauth
	AccessToken string
}

type PluginSpec struct {
	// Used programming lanuage
	Language string
	// Name of the project itself. In most cases it will be the same as the module name.
	Name string
	// Name of the software module. Needs to fullfil the requirements of the underlying programming language.
	ModuleName string
	// The name of the plugin within the cluster. Needs to fullfil the requirements of the resource names within k8s.
	PluginName string
	// Timestamp when project was autogenerated
	Timestamp string
	// The version of the generator used to create the project
	GeneratorVersion string
	// Informations about remote instances
	InstanceInformation InstanceInformation
}

type GeneratorSettings struct {
	ProjectFs embed.FS
	RootDir   string
	OutPath   string
}

type PluginGenerator interface {
	// writes the project to the given outpath
	CreateProject(outpath string, project PluginSpec) error
	// Writes the project to the given outpath, zips it and returns the path to the zip file
	// One has to takes care of cleaning up the (both) output paths.
	CreateProjectZip(outpath string, project PluginSpec) (string, error)
	// returns the generator id
	GeneratorId() string
	// returns a readbale name for the generator
	GeneratorReadableName() string
	// returns the programming language used by the generator
	GeneratorLanguage() string
}

// creates the project, zips it and returns the path to the zip file
func generateProjectZip(project PluginSpec, settings GeneratorSettings) (string, error) {
	err := createProject(project, settings)
	if err != nil {
		return "", err
	}

	tmpZipPath, err := os.MkdirTemp("", project.Name)

	if err != nil {
		return "", err
	}

	// create the zip file
	zip, err := utils.ZipFolder(settings.OutPath, tmpZipPath, project.Name)
	if err != nil {
		return "", err
	}

	return zip, nil
}

// internal method which templates the project files
func createProject(project PluginSpec, settings GeneratorSettings) error {
	err := verifyProjectSpec(project)
	if err != nil {
		return err
	}

	err = fs.WalkDir(settings.ProjectFs, settings.RootDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		writePath, err := getFolderName(path, project, settings)
		if err != nil {
			return fmt.Errorf("error getting folder name: %w", err)
		}

		if d.IsDir() {
			os.Mkdir(writePath, 0755)
		}

		if settings.isTemplateProjectFile(d) {
			// template the file
			t, err := template.ParseFS(settings.ProjectFs, path)
			if err != nil {
				return fmt.Errorf("error parsing template: %w", err)
			}

			filename := strings.TrimSuffix(writePath, templateSuffix)

			file, err := os.Create(filename)
			if err != nil {
				return fmt.Errorf("error creating file: %w", err)
			}
			defer file.Close()

			// Write the template to the file
			err = t.Execute(file, project)
			if err != nil {
				return fmt.Errorf("error executing template: %w", err)
			}
		} else if !d.IsDir() {
			// just copy the file
			srcFile, err := settings.ProjectFs.Open(path)
			if err != nil {
				return fmt.Errorf("error opening source file: %w", err)
			}
			defer srcFile.Close()

			dstFile, err := os.Create(writePath)
			if err != nil {
				return fmt.Errorf("error creating file: %w", err)
			}
			defer dstFile.Close()

			_, err = io.Copy(dstFile, srcFile)
			if err != nil {
				return fmt.Errorf("error copying file: %w", err)
			}
		}

		return nil
	})

	if err != nil {
		return fmt.Errorf("error walking the filesystem: %w", err)
	}
	return nil
}

func verifyProjectSpec(project PluginSpec) error {
	if len(strings.Trim(project.ModuleName, " ")) == 0 {
		return fmt.Errorf("module name cannot be empty")
	}
	if len(strings.Trim(project.Name, " ")) == 0 {
		return fmt.Errorf("project name cannot be empty")
	}
	return nil
}

func (settings GeneratorSettings) isTemplateProjectFile(entry fs.DirEntry) bool {
	return !entry.IsDir() && strings.HasSuffix(entry.Name(), templateSuffix)
}

func getFolderName(path string, spec PluginSpec, settings GeneratorSettings) (string, error) {
	outpath := settings.OutPath
	if outpath == "." {
		outpath = ""
	}

	if outpath != "" && !strings.HasSuffix(outpath, "/") {
		outpath = outpath + "/"
	}

	// we do not want to include the root dir in the path (e.g. PythonPlugin)
	path = strings.TrimPrefix(path, settings.RootDir)

	split := strings.Split(path, "/")
	newPathSplit := make([]string, len(split))

	// checks for the folder template and replaces it with the value from the project spec
	for index, item := range split {
		if strings.HasPrefix(item, folderTemplatePrefix) && strings.HasSuffix(item, folderTemplateSuffix) {
			value, err := replaceFolderNames(item, spec)
			if err != nil {
				return "", err
			}
			newPathSplit[index] = value
		} else {
			newPathSplit[index] = item
		}
	}
	return outpath + strings.Join(newPathSplit, "/"), nil
}

func replaceFolderNames(templ string, spec PluginSpec) (string, error) {
	t := reflect.TypeOf(spec)
	fields := reflect.VisibleFields(t)
	for _, field := range fields {
		templ, _ = strings.CutPrefix(templ, folderTemplatePrefix)
		templ, _ = strings.CutPrefix(templ, templatePrefix)
		templ, _ = strings.CutSuffix(templ, folderTemplateSuffix)

		if field.Name == templ {
			return reflect.ValueOf(spec).FieldByName(templ).String(), nil
		}
	}
	return "", fmt.Errorf("field %s not found in struct", templ)
}
