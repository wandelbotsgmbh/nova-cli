//go:build integration

// Integration tests for the podman runtime. They require a podman binary and
// a registry to push to (see the test-podman job in .github/workflows/ci.yml):
//
//	NOVA_TEST_REGISTRY: host:port of a registry (default localhost:5000).
//	  The registry must be marked insecure in registries.conf, e.g.:
//	  [[registry]]
//	  location = "localhost:5000"
//	  insecure = true
//
// Run with: go test -tags integration -run TestPodman ./pkg/docker/
package docker

import (
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func requirePodman(t *testing.T) {
	t.Helper()
	if _, err := exec.LookPath("podman"); err != nil {
		t.Skip("podman is not installed")
	}
}

func testRegistry() string {
	if reg := os.Getenv("NOVA_TEST_REGISTRY"); reg != "" {
		return reg
	}
	return "localhost:5000"
}

// writeTestProject creates a minimal build context. The Dockerfile is FROM
// scratch + COPY only, so it builds for any platform without emulation
// (same as the Dockerfile generated by 'nova model init').
func writeTestProject(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	dockerfile := "FROM scratch\nCOPY hello.txt /hello.txt\n"
	if err := os.WriteFile(filepath.Join(dir, "Dockerfile"), []byte(dockerfile), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "hello.txt"), []byte("hello from nova test"), 0644); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestPodmanDetectedWhenDockerAbsent(t *testing.T) {
	requirePodman(t)
	if _, err := exec.LookPath("docker"); err == nil {
		t.Skip("docker is installed, auto-detection prefers it")
	}

	rt, err := Detect("")
	if err != nil {
		t.Fatalf("Detect() failed: %v", err)
	}
	if rt.Name() != RuntimeNamePodman {
		t.Errorf("Detect() = %q, expected %q", rt.Name(), RuntimeNamePodman)
	}
}

func TestPodmanBuildAndPushImage(t *testing.T) {
	requirePodman(t)
	dir := writeTestProject(t)
	image := testRegistry() + "/nova-cli-test/app:latest"
	rt := podmanRuntime{}

	if err := rt.BuildImage(dir, image); err != nil {
		t.Fatalf("BuildImage() failed: %v", err)
	}

	digest, err := rt.PushImage(image)
	if err != nil {
		t.Fatalf("PushImage() failed: %v", err)
	}
	if !strings.HasPrefix(digest, "sha256:") {
		t.Errorf("PushImage() returned invalid digest %q", digest)
	}
}

func TestPodmanBuildAndPushMultiPlatform(t *testing.T) {
	requirePodman(t)
	dir := writeTestProject(t)
	image := testRegistry() + "/nova-cli-test/model:latest"
	rt := podmanRuntime{}

	// twice, to verify rebuilding does not accumulate manifest entries
	for range 2 {
		if err := rt.BuildAndPushMultiPlatform(filepath.Join(dir, "Dockerfile"), dir, image); err != nil {
			t.Fatalf("BuildAndPushMultiPlatform() failed: %v", err)
		}
	}

	// remove the local manifest list so the inspect below reads the pushed
	// one from the registry instead of local storage
	if out, err := exec.Command("podman", "manifest", "rm", image).CombinedOutput(); err != nil {
		t.Fatalf("podman manifest rm failed: %v: %s", err, out)
	}

	out, err := exec.Command("podman", "manifest", "inspect", image).Output()
	if err != nil {
		t.Fatalf("podman manifest inspect failed: %v", err)
	}
	var manifest struct {
		Manifests []struct {
			Platform struct {
				OS           string `json:"os"`
				Architecture string `json:"architecture"`
			} `json:"platform"`
		} `json:"manifests"`
	}
	if err := json.Unmarshal(out, &manifest); err != nil {
		t.Fatalf("failed to parse manifest list: %v", err)
	}

	var platforms []string
	for _, m := range manifest.Manifests {
		platforms = append(platforms, m.Platform.OS+"/"+m.Platform.Architecture)
	}
	if len(platforms) != 2 || !strings.Contains(strings.Join(platforms, ","), "linux/amd64") || !strings.Contains(strings.Join(platforms, ","), "linux/arm64") {
		t.Errorf("expected exactly linux/amd64 and linux/arm64 in manifest list, got %v", platforms)
	}
}

func TestPodmanLoginCredentials(t *testing.T) {
	requirePodman(t)
	registry := testRegistry()

	loginCmd := exec.Command("podman", "login", "--tls-verify=false", "-u", "testuser", "-p", "testsecret", registry)
	if out, err := loginCmd.CombinedOutput(); err != nil {
		t.Fatalf("podman login failed: %v: %s", err, out)
	}
	t.Cleanup(func() {
		_ = exec.Command("podman", "logout", registry).Run()
	})

	creds, err := podmanRuntime{}.GetRegistryCredentials(registry + "/nova-cli-test/app")
	if err != nil {
		t.Fatalf("GetRegistryCredentials() failed: %v", err)
	}
	if creds.Username != "testuser" || creds.Password != "testsecret" {
		t.Errorf("unexpected credentials: %s/%s", creds.Username, creds.Password)
	}
}
